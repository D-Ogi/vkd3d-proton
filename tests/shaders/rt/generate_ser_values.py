"""Generate the SER GPU test header from the pinned translator's regression inputs."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--dxc', type=Path, required=True)
p.add_argument('--assembler', type=Path, required=True)
p.add_argument('--output', type=Path, required=True)
a = p.parse_args()
a.output.mkdir(parents=True, exist_ok=True)
if any(a.output.iterdir()):
    p.error('--output must be empty')
here = Path(__file__).resolve().parent
probes = here.parents[2] / 'subprojects/dxil-spirv/tests/ser-values'
names = ['CopyLive', 'TwoPhi', 'UnboundPhi', 'UnboundRoot', 'DirectPayloadControl',
         'LoopLive', 'ArrayLive', 'HelperLive', 'HintOnly', 'TempAlias', 'BoundRoot', 'ser_values_support']
records = []
header = ['/* Generated by generate_ser_values.py. */']
def run(args):
    args = [str(x) for x in args]
    subprocess.run(args, check=True)
    return args
def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()
for name in names:
    binary = a.output / (name + '.dxil')
    if name == 'TempAlias':
        source = probes / 'TempAlias.ll'
        cmd = run([a.assembler, a.dxc.parent, source, binary])
    else:
        source = probes / (name + '.hlsl')
        if name == 'BoundRoot': source = here / 'ser_values_bound_root.lib_6_9.hlsl'
        if name == 'ser_values_support': source = here / 'ser_values_support.lib_6_9.hlsl'
        cmd = run([a.dxc, '-T', 'lib_6_9', '-HV', '2021', '-Fo', binary, source])
    validation = run([a.dxc.parent / 'dxv.exe', binary])
    records.append(dict(source=str(source), source_sha256=sha(source), binary=str(binary),
                        binary_sha256=sha(binary), command=cmd, validation=validation))
    data = binary.read_bytes()
    header += [f'static const unsigned char ser_{name}_data[] = {{',
               ',\n'.join(','.join(f'0x{x:02x}' for x in data[i:i+24]) for i in range(0, len(data), 24)),
               '};', f'static const D3D12_SHADER_BYTECODE ser_{name} = {{ser_{name}_data, sizeof(ser_{name}_data)}};']
(here / 'headers/ser_values.h').write_text('\n'.join(header) + '\n', encoding='utf-8')
(a.output / 'commands.json').write_text(json.dumps(dict(dxc_sha256=sha(a.dxc), dxcompiler_sha256=sha(a.dxc.parent/'dxcompiler.dll'),
    assembler_sha256=sha(a.assembler), shaders=records), indent=2) + '\n', encoding='utf-8')
